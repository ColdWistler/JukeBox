#!/usr/bin/env node
// Regenerates manifest.js from whatever is inside Music/.
// manifest.js is the ONLY thing script.js reads to build the playlist,
// so it must be regenerated and committed whenever Music/ changes.
import { readdirSync, writeFileSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";

const AUDIO_EXT = /\.(mp3|wav|ogg|oga|m4a|aac|flac|opus|webm)$/i;
const DIR = "Music";

// Walk Music/ recursively so songs in subfolders are picked up too.
function walk(dir, acc = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walk(full, acc);
    else if (AUDIO_EXT.test(entry.name)) acc.push(full);
  }
  return acc;
}

let files = [];
try {
  statSync(DIR);
  files = walk(DIR);
} catch {
  console.error(DIR + "/ not found — wrote an empty manifest.js");
}

// Store repo-relative POSIX paths, sorted case-insensitively for a stable diff.
files = files
  .map((f) => relative(DIR, f).split(sep).join("/"))
  .sort((a, b) => a.toLowerCase().localeCompare(b.toLowerCase()));

writeFileSync(
  "manifest.js",
  "// AUTO-GENERATED by gen-manifest.mjs — do not edit by hand.\n" +
    "const MANIFEST = [\n" +
    files.map((f) => "  " + JSON.stringify(f) + ",").join("\n") +
    "\n];\n"
);

console.log("manifest.js written with " + files.length + " song(s)");
